  /* 4. จัดการสถานะใบงาน (__ws) และแปลงเป็นข้อความส่งครู/AI */
  const esc = v => String(v ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

  function defaultWsState(chNo) {
    const schema = CHAPTER_SCHEMAS[chNo];
    const data = {};
    if (schema) {
      schema.sections.forEach(sec => {
        if (sec.type === 'table') {
          if (sec.topField) data[sec.topField.id] = '';
          if (sec.bottomField) data[sec.bottomField.id] = '';
          sec.rows.forEach(r => {
            sec.columns.forEach(col => {
              data[r.id + '_' + col.id] = col.type === 'select' ? col.options[0] : '';
            });
          });
        } else if (sec.type === 'bullets' || sec.type === 'fields') {
          sec.items.forEach(it => { data[it.id] = ''; });
        }
      });
    }
    return {
      v: 3,
      ch: Number(chNo),
      data,
      canvas: {
        stamps: [],
        strokes: [],
        shapes: [],
        labels: [],
        bgGrid: true
      },
      photo: '',
      photoCaption: ''
    };
  }

  function parseWsState(chNo, fieldsObj) {
    const base = defaultWsState(chNo);
    if (!fieldsObj || typeof fieldsObj !== 'object') return base;
    if (fieldsObj.__ws && typeof fieldsObj.__ws === 'string') {
      try {
        const parsed = JSON.parse(fieldsObj.__ws);
        if (parsed && typeof parsed === 'object') {
          base.data = Object.assign(base.data, parsed.data || {});
          if (parsed.canvas && typeof parsed.canvas === 'object') {
            base.canvas.stamps = Array.isArray(parsed.canvas.stamps) ? parsed.canvas.stamps : [];
            base.canvas.strokes = Array.isArray(parsed.canvas.strokes) ? parsed.canvas.strokes : [];
            base.canvas.shapes = Array.isArray(parsed.canvas.shapes) ? parsed.canvas.shapes : [];
            base.canvas.labels = Array.isArray(parsed.canvas.labels) ? parsed.canvas.labels : [];
            base.canvas.bgGrid = parsed.canvas.bgGrid !== false;
          }
          base.photo = typeof parsed.photo === 'string' ? parsed.photo : '';
          base.photoCaption = typeof parsed.photoCaption === 'string' ? parsed.photoCaption : '';
        }
      } catch (e) { /* ignore malformed json */ }
    }
    return base;
  }

  function hasCanvasContent(ws) {
    if (!ws || !ws.canvas) return false;
    return (ws.canvas.stamps && ws.canvas.stamps.length > 0) ||
           (ws.canvas.strokes && ws.canvas.strokes.length > 0) ||
           (ws.canvas.shapes && ws.canvas.shapes.length > 0) ||
           (ws.canvas.labels && ws.canvas.labels.length > 0);
  }

  function summarizeCanvas(ws) {
    if (!ws) return '';
    const parts = [];
    if (ws.canvas) {
      if (ws.canvas.stamps && ws.canvas.stamps.length) {
        parts.push('อีโมจิบนกระดาน: ' + ws.canvas.stamps.map(s => s.emoji).join(' '));
      }
      if (ws.canvas.labels && ws.canvas.labels.length) {
        parts.push('ป้ายชี้จุด: ' + ws.canvas.labels.map(l => '"' + l.text + '"').join(', '));
      }
      if ((ws.canvas.strokes && ws.canvas.strokes.length) || (ws.canvas.shapes && ws.canvas.shapes.length)) {
        parts.push('มีเส้นวาดประกอบ');
      }
    }
    if (ws.photo) {
      parts.push('แนบภาพถ่าย 1 ภาพ' + (ws.photoCaption ? ' (' + ws.photoCaption + ')' : ''));
    }
    return parts.length ? '[กระดานออกแบบ: ' + parts.join(' | ') + ']' : '';
  }

  function synthesizeFieldTexts(chNo, ws, existingFields) {
    const schema = CHAPTER_SCHEMAS[chNo];
    if (!schema) return;
    const d = ws.data || {};
    const canvasNote = summarizeCanvas(ws);

    schema.sections.forEach(sec => {
      const lines = [];
      if (sec.type === 'table') {
        if (sec.topField) {
          const tv = (d[sec.topField.id] || '').trim();
          if (tv) lines.push('• ' + sec.topField.label + ': ' + tv);
        }
        let filledRows = 0;
        sec.rows.forEach(r => {
          const cellParts = [];
          let hasNonSelectText = false;
          sec.columns.forEach(col => {
            const val = String(d[r.id + '_' + col.id] || '').trim();
            if (col.type !== 'select' && val) hasNonSelectText = true;
            if (val) cellParts.push(col.label + ': ' + val);
          });
          if (hasNonSelectText) {
            filledRows++;
            lines.push('• ' + r.label + ' ' + cellParts.join(' | '));
          }
        });
        if (sec.bottomField) {
          const bv = (d[sec.bottomField.id] || '').trim();
          if (bv) lines.push('• ' + sec.bottomField.label + ': ' + bv);
        }
        if (filledRows === 0 && !lines.length) {
          existingFields[sec.key] = '';
          return;
        }
      } else if (sec.type === 'bullets' || sec.type === 'fields') {
        sec.items.forEach(it => {
          const val = String(d[it.id] || '').trim();
          if (val) lines.push('• ' + it.label + ': ' + val);
        });
      }

      if (schema.studio && schema.studio.targetField === sec.key && canvasNote) {
        lines.push(canvasNote);
      }

      existingFields[sec.key] = lines.join('\n').slice(0, 11500);
    });

    if (!existingFields.evidenceMode) {
      existingFields.evidenceMode = schema.defaultEvidence || 'การสำรวจและการวิเคราะห์';
    }
    try {
      existingFields.__ws = JSON.stringify(ws);
    } catch (e) { /* ignore */ }
  }

  /* 5. วาดกระดานออกแบบสร้างสรรค์ลงบน HTML5 Canvas */
  function renderStudioCanvas(canvasEl, ws, activeSelection, opts = {}) {
    if (!canvasEl) return;
    const rect = canvasEl.getBoundingClientRect();
    const cssW = opts.fixedWidth || Math.max(300, rect.width || 640);
    const cssH = opts.fixedHeight || Math.max(220, rect.height || 320);
    const ratio = opts.exportRatio || Math.min(window.devicePixelRatio || 1, 2);
    canvasEl.width = Math.round(cssW * ratio);
    canvasEl.height = Math.round(cssH * ratio);
    const ctx = canvasEl.getContext('2d');
    ctx.save();
    ctx.scale(ratio, ratio);

    ctx.fillStyle = '#fffdf9';
    ctx.fillRect(0, 0, cssW, cssH);

    if (!ws.canvas || ws.canvas.bgGrid !== false) {
      ctx.strokeStyle = 'rgba(71, 112, 148, 0.10)';
      ctx.lineWidth = 1;
      const step = 24;
      for (let x = step; x < cssW; x += step) {
        ctx.beginPath(); ctx.moveTo(x, 0); ctx.lineTo(x, cssH); ctx.stroke();
      }
      for (let y = step; y < cssH; y += step) {
        ctx.beginPath(); ctx.moveTo(0, y); ctx.lineTo(cssW, y); ctx.stroke();
      }
    }

    const cv = (ws && ws.canvas) || {};

    (cv.strokes || []).forEach(st => {
      const pts = Array.isArray(st) ? st : st.points;
      if (!pts || !pts.length) return;
      ctx.save();
      ctx.strokeStyle = st.color || '#264653';
      ctx.lineWidth = st.size || 3;
      ctx.lineCap = 'round';
      ctx.lineJoin = 'round';
      ctx.beginPath();
      ctx.moveTo(pts[0][0] * cssW, pts[0][1] * cssH);
      for (let i = 1; i < pts.length; i++) {
        ctx.lineTo(pts[i][0] * cssW, pts[i][1] * cssH);
      }
      ctx.stroke();
      ctx.restore();
    });

    (cv.shapes || []).forEach((sh, idx) => {
      ctx.save();
      ctx.strokeStyle = sh.color || '#1d3557';
      ctx.fillStyle = sh.color || '#1d3557';
      ctx.lineWidth = sh.size || 3;
      ctx.lineCap = 'round';
      ctx.lineJoin = 'round';
      const x1 = sh.x1 * cssW, y1 = sh.y1 * cssH, x2 = sh.x2 * cssW, y2 = sh.y2 * cssH;
      if (sh.type === 'line' || sh.type === 'arrow') {
        ctx.beginPath();
        ctx.moveTo(x1, y1);
        ctx.lineTo(x2, y2);
        ctx.stroke();
        if (sh.type === 'arrow') {
          const angle = Math.atan2(y2 - y1, x2 - x1);
          const headLen = 12;
          ctx.beginPath();
          ctx.moveTo(x2, y2);
          ctx.lineTo(x2 - headLen * Math.cos(angle - Math.PI / 6), y2 - headLen * Math.sin(angle - Math.PI / 6));
          ctx.lineTo(x2 - headLen * Math.cos(angle + Math.PI / 6), y2 - headLen * Math.sin(angle + Math.PI / 6));
          ctx.closePath();
          ctx.fill();
        }
      } else if (sh.type === 'rect') {
        ctx.strokeRect(Math.min(x1, x2), Math.min(y1, y2), Math.abs(x2 - x1), Math.abs(y2 - y1));
      } else if (sh.type === 'circle') {
        const rx = Math.abs(x2 - x1) / 2, ry = Math.abs(y2 - y1) / 2;
        const cx = (x1 + x2) / 2, cy = (y1 + y2) / 2;
        ctx.beginPath();
        ctx.ellipse(cx, cy, Math.max(2, rx), Math.max(2, ry), 0, 0, Math.PI * 2);
        ctx.stroke();
      }
      if (activeSelection && activeSelection.kind === 'shape' && activeSelection.index === idx) {
        ctx.strokeStyle = '#e76f51';
        ctx.lineWidth = 1.5;
        ctx.setLineDash([4, 4]);
        ctx.strokeRect(Math.min(x1, x2) - 6, Math.min(y1, y2) - 6, Math.abs(x2 - x1) + 12, Math.abs(y2 - y1) + 12);
      }
      ctx.restore();
    });

    (cv.stamps || []).forEach((st, idx) => {
      const cx = (st.x ?? 0.5) * cssW;
      const cy = (st.y ?? 0.5) * cssH;
      const sz = Number(st.size) || 46;
      const rot = (Number(st.rot) || 0) * Math.PI / 180;
      const flip = st.flip ? -1 : 1;
      ctx.save();
      ctx.translate(cx, cy);
      ctx.rotate(rot);
      ctx.scale(flip, 1);
      ctx.font = `${sz}px "Segoe UI Emoji", "Apple Color Emoji", "Noto Color Emoji", sans-serif`;
      ctx.textAlign = 'center';
      ctx.textBaseline = 'middle';
      ctx.fillText(st.emoji || '⚙️', 0, 0);
      ctx.restore();

      if (activeSelection && activeSelection.kind === 'stamp' && activeSelection.index === idx) {
        ctx.save();
        ctx.strokeStyle = '#e76f51';
        ctx.lineWidth = 2;
        ctx.setLineDash([5, 3]);
        ctx.strokeRect(cx - sz * 0.62, cy - sz * 0.62, sz * 1.24, sz * 1.24);
        ctx.restore();
      }
    });

    (cv.labels || []).forEach((lb, idx) => {
      const lx = (lb.x ?? 0.5) * cssW;
      const ly = (lb.y ?? 0.5) * cssH;
      const text = String(lb.text || 'ป้ายข้อความ');
      ctx.save();
      ctx.font = '600 13px "Kanit", "Sarabun", sans-serif';
      const tw = Math.min(cssW - 24, ctx.measureText(text).width + 18);
      const th = 26;
      const bx = Math.max(6, Math.min(cssW - tw - 6, lx - tw / 2));
      const by = Math.max(6, Math.min(cssH - th - 6, ly - th / 2));

      ctx.fillStyle = lb.bg || '#fff3cd';
      ctx.strokeStyle = (activeSelection && activeSelection.kind === 'label' && activeSelection.index === idx) ? '#e76f51' : '#d4a373';
      ctx.lineWidth = (activeSelection && activeSelection.kind === 'label' && activeSelection.index === idx) ? 2.2 : 1.4;
      ctx.beginPath();
      if (ctx.roundRect) ctx.roundRect(bx, by, tw, th, 6);
      else ctx.rect(bx, by, tw, th);
      ctx.fill();
      ctx.stroke();

      ctx.fillStyle = '#1f2933';
      ctx.textAlign = 'center';
      ctx.textBaseline = 'middle';
      ctx.fillText(text, bx + tw / 2, by + th / 2 + 1);
      ctx.restore();
    });

    if (!hasCanvasContent(ws) && !opts.forPrint) {
      ctx.save();
      ctx.fillStyle = 'rgba(74, 85, 104, 0.50)';
      ctx.font = '500 14px "Kanit", "Sarabun", sans-serif';
      ctx.textAlign = 'center';
      ctx.fillText('คลิกอีโมจิด้านล่างเพื่อวางบนกระดาน หรือใช้วาดเส้น/ลูกศร/ติดป้ายชี้จุด', cssW / 2, cssH / 2);
      ctx.restore();
    }

    ctx.restore();
  }

