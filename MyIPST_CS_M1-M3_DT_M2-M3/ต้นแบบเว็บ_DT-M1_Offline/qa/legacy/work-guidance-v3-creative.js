  /* 11. ผูก Event การโต้ตอบทั้งหมดของใบงานและกระดานออกแบบสร้างสรรค์ */
  let activeCleanup = null;

  function mountWorkPage(c, w, onUpdateAndSave) {
    activeCleanup?.();
    activeCleanup = null;

    const root = document.querySelector(`[data-ws-chapter="${c.number}"]`);
    if (!root) return;

    const chNo = c.number;
    const schema = CHAPTER_SCHEMAS[chNo];
    let ws = parseWsState(chNo, w.fields);

    synthesizeFieldTexts(chNo, ws, w.fields);

    const canvas = root.querySelector('#ws-creative-canvas');
    const selBar = root.querySelector('#ws-selected-bar');
    const selTitle = root.querySelector('#ws-sel-title');
    const editLabelBtn = root.querySelector('#ws-btn-edit-label');

    let tool = 'select';
    let selection = null;
    let draggingItem = false;
    let dragOffset = [0, 0];
    let drawingStroke = null;
    let drawingShape = null;

    function commitChange(redraw = false) {
      synthesizeFieldTexts(chNo, ws, w.fields);
      if (redraw && canvas) renderStudioCanvas(canvas, ws, selection);
      onUpdateAndSave?.();
    }

    function updateSelectionUI() {
      if (!selBar) return;
      if (!selection) {
        selBar.hidden = true;
        return;
      }
      selBar.hidden = false;
      if (selection.kind === 'stamp') {
        const st = ws.canvas.stamps[selection.index];
        selTitle.textContent = `เลือกอีโมจิ ${st ? st.emoji : ''} (ลากย้ายได้)`;
        if (editLabelBtn) editLabelBtn.hidden = true;
      } else if (selection.kind === 'label') {
        const lb = ws.canvas.labels[selection.index];
        selTitle.textContent = `ป้าย "${lb ? lb.text : ''}"`;
        if (editLabelBtn) editLabelBtn.hidden = false;
      } else if (selection.kind === 'shape') {
        selTitle.textContent = 'เลือกรูปทรง/ลูกศร';
        if (editLabelBtn) editLabelBtn.hidden = true;
      }
    }

    function setTool(newTool) {
      tool = newTool;
      root.querySelectorAll('[data-ws-tool]').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.wsTool === tool);
      });
      if (tool !== 'select') {
        selection = null;
        updateSelectionUI();
        renderStudioCanvas(canvas, ws, selection);
      }
    }

    function normCoord(e) {
      const r = canvas.getBoundingClientRect();
      return [
        Math.max(0.02, Math.min(0.98, (e.clientX - r.left) / Math.max(1, r.width))),
        Math.max(0.04, Math.min(0.96, (e.clientY - r.top) / Math.max(1, r.height)))
      ];
    }

    function hitTest(nx, ny) {
      const r = canvas.getBoundingClientRect();
      const px = nx * r.width, py = ny * r.height;

      for (let i = (ws.canvas.labels || []).length - 1; i >= 0; i--) {
        const lb = ws.canvas.labels[i];
        const lx = lb.x * r.width, ly = lb.y * r.height;
        const hw = Math.max(48, (lb.text || '').length * 5.5);
        if (Math.abs(px - lx) <= hw && Math.abs(py - ly) <= 18) {
          return { kind: 'label', index: i };
        }
      }
      for (let i = (ws.canvas.stamps || []).length - 1; i >= 0; i--) {
        const st = ws.canvas.stamps[i];
        const sx = st.x * r.width, sy = st.y * r.height;
        const rad = (Number(st.size) || 46) * 0.6;
        if (Math.abs(px - sx) <= rad && Math.abs(py - sy) <= rad) {
          return { kind: 'stamp', index: i };
        }
      }
      for (let i = (ws.canvas.shapes || []).length - 1; i >= 0; i--) {
        const sh = ws.canvas.shapes[i];
        const minX = Math.min(sh.x1, sh.x2) * r.width - 10;
        const maxX = Math.max(sh.x1, sh.x2) * r.width + 10;
        const minY = Math.min(sh.y1, sh.y2) * r.height - 10;
        const maxY = Math.max(sh.y1, sh.y2) * r.height + 10;
        if (px >= minX && px <= maxX && py >= minY && py <= maxY) {
          return { kind: 'shape', index: i };
        }
      }
      return null;
    }

    const onInput = e => {
      const t = e.target;
      if (t.matches('[data-ws-input]')) {
        ws.data[t.dataset.wsInput] = t.value;
        commitChange(false);
      } else if (t.matches('[data-ws-photo-cap]')) {
        ws.photoCaption = t.value;
        commitChange(false);
      }
    };
    root.addEventListener('input', onInput);
    root.addEventListener('change', onInput);

    const onClick = e => {
      const presetBtn = e.target.closest('[data-ws-preset]');
      if (presetBtn) {
        const pIdx = presetBtn.dataset.wsPreset;
        if (pIdx === 'clear') {
          if (!confirm('ล้างข้อความและกระดานเพื่อเริ่มเขียนใหม่หรือไม่?')) return;
          ws = defaultWsState(chNo);
        } else {
          const pr = schema?.presets?.[Number(pIdx)];
          if (!pr) return;
          ws.data = Object.assign(defaultWsState(chNo).data, structuredClone(pr.data || {}));
          ws.canvas.stamps = structuredClone(pr.stamps || []);
          ws.canvas.labels = structuredClone(pr.labels || []);
          ws.canvas.strokes = [];
          ws.canvas.shapes = [];
        }
        root.querySelectorAll('[data-ws-input]').forEach(el => {
          const k = el.dataset.wsInput;
          el.value = ws.data[k] ?? '';
        });
        selection = null;
        updateSelectionUI();
        commitChange(true);
        return;
      }

      const catBtn = e.target.closest('[data-ws-cat]');
      if (catBtn) {
        const cid = catBtn.dataset.wsCat;
        root.querySelectorAll('[data-ws-cat]').forEach(b => b.classList.toggle('active', b.dataset.wsCat === cid));
        root.querySelectorAll('[data-ws-cat-panel]').forEach(p => p.classList.toggle('active', p.dataset.wsCatPanel === cid));
        return;
      }

      const stampBtn = e.target.closest('[data-ws-stamp]');
      if (stampBtn) {
        const em = stampBtn.dataset.wsStamp;
        const count = ws.canvas.stamps.length;
        const nx = 0.22 + ((count * 0.13) % 0.58);
        const ny = 0.32 + ((Math.floor(count / 5) * 0.18) % 0.42);
        ws.canvas.stamps.push({ emoji: em, x: nx, y: ny, size: 48, rot: 0, flip: false });
        setTool('select');
        selection = { kind: 'stamp', index: ws.canvas.stamps.length - 1 };
        updateSelectionUI();
        commitChange(true);
        return;
      }

      const toolBtn = e.target.closest('[data-ws-tool]');
      if (toolBtn) {
        setTool(toolBtn.dataset.wsTool);
        return;
      }

      const opBtn = e.target.closest('[data-ws-item-op]');
      if (opBtn && selection) {
        const op = opBtn.dataset.wsItemOp;
        if (selection.kind === 'stamp') {
          const st = ws.canvas.stamps[selection.index];
          if (!st) return;
          if (op === 'bigger') st.size = Math.min(110, (Number(st.size) || 48) + 8);
          else if (op === 'smaller') st.size = Math.max(22, (Number(st.size) || 48) - 8);
          else if (op === 'rot-l') st.rot = ((Number(st.rot) || 0) - 15) % 360;
          else if (op === 'rot-r') st.rot = ((Number(st.rot) || 0) + 15) % 360;
          else if (op === 'flip') st.flip = !st.flip;
          else if (op === 'delete') {
            ws.canvas.stamps.splice(selection.index, 1);
            selection = null;
          }
        } else if (selection.kind === 'label') {
          const lb = ws.canvas.labels[selection.index];
          if (!lb) return;
          if (op === 'edit-text') {
            const txt = prompt('แก้ไขข้อความป้ายชี้จุด:', lb.text || '');
            if (txt !== null && txt.trim()) lb.text = txt.trim().slice(0, 60);
          } else if (op === 'delete') {
            ws.canvas.labels.splice(selection.index, 1);
            selection = null;
          }
        } else if (selection.kind === 'shape') {
          if (op === 'delete') {
            ws.canvas.shapes.splice(selection.index, 1);
            selection = null;
          }
        }
        updateSelectionUI();
        commitChange(true);
        return;
      }

      const actBtn = e.target.closest('[data-ws-action]');
      if (actBtn) {
        const act = actBtn.dataset.wsAction;
        if (act === 'add-label') {
          const txt = prompt('พิมพ์ข้อความป้ายชี้จุด (เช่น ขนาด 20 ซม. / ถาดรองน้ำ):', 'จุดสำคัญ');
          if (txt && txt.trim()) {
            ws.canvas.labels.push({ text: txt.trim().slice(0, 60), x: 0.5, y: 0.22 + (ws.canvas.labels.length * 0.12) % 0.6 });
            setTool('select');
            selection = { kind: 'label', index: ws.canvas.labels.length - 1 };
            updateSelectionUI();
            commitChange(true);
          }
        } else if (act === 'add-custom-emoji') {
          const inp = root.querySelector('#ws-custom-emoji-input');
          const val = (inp?.value || '').trim();
          if (!val) return;
          ws.canvas.stamps.push({ emoji: val.slice(0, 6), x: 0.5, y: 0.5, size: 48, rot: 0, flip: false });
          if (inp) inp.value = '';
          setTool('select');
          selection = { kind: 'stamp', index: ws.canvas.stamps.length - 1 };
          updateSelectionUI();
          commitChange(true);
        } else if (act === 'undo-canvas') {
          if (ws.canvas.strokes.length) ws.canvas.strokes.pop();
          else if (ws.canvas.shapes.length) ws.canvas.shapes.pop();
          else if (ws.canvas.labels.length) ws.canvas.labels.pop();
          else if (ws.canvas.stamps.length) ws.canvas.stamps.pop();
          selection = null;
          updateSelectionUI();
          commitChange(true);
        } else if (act === 'clear-canvas') {
          if (!confirm('ล้างภาพและอีโมจิทั้งหมดบนกระดานหรือไม่?')) return;
          ws.canvas = { stamps: [], strokes: [], shapes: [], labels: [], bgGrid: ws.canvas.bgGrid };
          selection = null;
          updateSelectionUI();
          commitChange(true);
        } else if (act === 'remove-photo') {
          ws.photo = '';
          ws.photoCaption = '';
          const prevArea = root.querySelector('#ws-photo-preview-area');
          if (prevArea) prevArea.hidden = true;
          commitChange(false);
        }
      }
    };
    root.addEventListener('click', onClick);

    const photoInput = root.querySelector('#ws-photo-input');
    if (photoInput) {
      photoInput.addEventListener('change', async e => {
        const f = e.target.files?.[0];
        if (!f) return;
        try {
          const dataUrl = await compressPhotoFile(f);
          ws.photo = dataUrl;
          const prevArea = root.querySelector('#ws-photo-preview-area');
          const img = root.querySelector('#ws-photo-img');
          if (img) img.src = dataUrl;
          if (prevArea) prevArea.hidden = false;
          commitChange(false);
        } catch (err) {
          window.DTApp?.notify(err.message || 'อัปโหลดรูปไม่สำเร็จ');
        }
      });
    }

    if (canvas) {
      canvas.addEventListener('pointerdown', e => {
        const [nx, ny] = normCoord(e);
        const strokeColor = root.querySelector('#ws-stroke-color')?.value || '#1d3557';

        if (tool === 'select') {
          const hit = hitTest(nx, ny);
          selection = hit;
          updateSelectionUI();
          if (hit) {
            draggingItem = true;
            canvas.setPointerCapture(e.pointerId);
            if (hit.kind === 'stamp') {
              const st = ws.canvas.stamps[hit.index];
              dragOffset = [nx - st.x, ny - st.y];
            } else if (hit.kind === 'label') {
              const lb = ws.canvas.labels[hit.index];
              dragOffset = [nx - lb.x, ny - lb.y];
            } else if (hit.kind === 'shape') {
              const sh = ws.canvas.shapes[hit.index];
              dragOffset = [nx - sh.x1, ny - sh.y1, sh.x2 - sh.x1, sh.y2 - sh.y1];
            }
          }
          renderStudioCanvas(canvas, ws, selection);
        } else if (tool === 'pen') {
          canvas.setPointerCapture(e.pointerId);
          drawingStroke = { color: strokeColor, size: 3, points: [[nx, ny]] };
          ws.canvas.strokes.push(drawingStroke);
          renderStudioCanvas(canvas, ws, selection);
        } else if (['arrow', 'rect', 'circle'].includes(tool)) {
          canvas.setPointerCapture(e.pointerId);
          drawingShape = { type: tool, color: strokeColor, size: 3, x1: nx, y1: ny, x2: nx, y2: ny };
          ws.canvas.shapes.push(drawingShape);
          renderStudioCanvas(canvas, ws, selection);
        }
      });

      canvas.addEventListener('pointermove', e => {
        if (!draggingItem && !drawingStroke && !drawingShape) return;
        const [nx, ny] = normCoord(e);
        if (draggingItem && selection) {
          if (selection.kind === 'stamp') {
            const st = ws.canvas.stamps[selection.index];
            if (st) {
              st.x = Math.max(0.04, Math.min(0.96, nx - dragOffset[0]));
              st.y = Math.max(0.06, Math.min(0.94, ny - dragOffset[1]));
            }
          } else if (selection.kind === 'label') {
            const lb = ws.canvas.labels[selection.index];
            if (lb) {
              lb.x = Math.max(0.06, Math.min(0.94, nx - dragOffset[0]));
              lb.y = Math.max(0.06, Math.min(0.94, ny - dragOffset[1]));
            }
          } else if (selection.kind === 'shape') {
            const sh = ws.canvas.shapes[selection.index];
            if (sh) {
              sh.x1 = nx - dragOffset[0];
              sh.y1 = ny - dragOffset[1];
              sh.x2 = sh.x1 + dragOffset[2];
              sh.y2 = sh.y1 + dragOffset[3];
            }
          }
          renderStudioCanvas(canvas, ws, selection);
        } else if (drawingStroke) {
          if (drawingStroke.points.length < 1200) {
            drawingStroke.points.push([nx, ny]);
            renderStudioCanvas(canvas, ws, selection);
          }
        } else if (drawingShape) {
          drawingShape.x2 = nx;
          drawingShape.y2 = ny;
          renderStudioCanvas(canvas, ws, selection);
        }
      });

      const endPointer = () => {
        if (draggingItem || drawingStroke || drawingShape) {
          draggingItem = false;
          drawingStroke = null;
          drawingShape = null;
          commitChange(true);
        }
      };
      canvas.addEventListener('pointerup', endPointer);
      canvas.addEventListener('pointercancel', endPointer);

      canvas.addEventListener('dblclick', e => {
        const [nx, ny] = normCoord(e);
        const hit = hitTest(nx, ny);
        if (hit && hit.kind === 'label') {
          const lb = ws.canvas.labels[hit.index];
          const txt = prompt('แก้ไขข้อความป้ายชี้จุด:', lb.text || '');
          if (txt !== null && txt.trim()) {
            lb.text = txt.trim().slice(0, 60);
            commitChange(true);
          }
        }
      });
    }

    const onResize = () => {
      if (canvas) renderStudioCanvas(canvas, ws, selection);
    };
    window.addEventListener('resize', onResize);
    setTimeout(onResize, 20);

    activeCleanup = () => {
      window.removeEventListener('resize', onResize);
    };
  }

  window.DTWorksheet = {
    schemas: CHAPTER_SCHEMAS,
    renderWorkPage,
    mountWorkPage,
    renderSubmissionReadonly,
    printWorksheetA4,
    synthesizeFieldTexts,
    parseWsState
  };
