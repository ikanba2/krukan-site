  /* 6. บีบอัดภาพถ่ายอัตโนมัติ (สูงสุด 1 ภาพ) */
  function compressPhotoFile(file) {
    return new Promise((resolve, reject) => {
      if (!file || !file.type.startsWith('image/')) {
        reject(new Error('กรุณาเลือกไฟล์รูปภาพเท่านั้น'));
        return;
      }
      const reader = new FileReader();
      reader.onload = () => {
        const img = new Image();
        img.onload = () => {
          const maxDim = 520;
          let w = img.width, h = img.height;
          if (w > maxDim || h > maxDim) {
            if (w > h) { h = Math.round(h * maxDim / w); w = maxDim; }
            else { w = Math.round(w * maxDim / h); h = maxDim; }
          }
          const canvas = document.createElement('canvas');
          canvas.width = w;
          canvas.height = h;
          const ctx = canvas.getContext('2d');
          ctx.fillStyle = '#ffffff';
          ctx.fillRect(0, 0, w, h);
          ctx.drawImage(img, 0, 0, w, h);
          let q = 0.70;
          let dataUrl = canvas.toDataURL('image/jpeg', q);
          while (dataUrl.length > 28000 && q > 0.30) {
            q -= 0.10;
            dataUrl = canvas.toDataURL('image/jpeg', q);
          }
          resolve(dataUrl);
        };
        img.onerror = () => reject(new Error('อ่านไฟล์รูปภาพไม่สำเร็จ'));
        img.src = reader.result;
      };
      reader.onerror = () => reject(new Error('เปิดไฟล์ไม่สำเร็จ'));
      reader.readAsDataURL(file);
    });
  }

