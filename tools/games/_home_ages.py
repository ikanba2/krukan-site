a = s.index('    const ACTIVITY_INFO={\n'); b = s.index('    };\n', a)
block = s[a:b]
lines = block.split('\n'); done = set()
for i, ln in enumerate(lines):
    m = re.match(r'^(\s+)(["\'])(.+?)\2:\{(.*)\}(,?)$', ln)
    if not m: continue
    indent, q, key, body, comma = m.groups()
    hit = next((x for x in AGES if x[0].lower() in key.lower()), None)
    if not hit: continue
    _, grade, years, brief = hit; aud = grade + (' (ประเมิน)' if 'ประเมิน' in years else '')
    body = re.sub(r',?\s*(["\']?)(audience|brief)\1:(["\']).*?\3', '', body)         # เอาค่าเดิมของสองช่องออก
    body = body.lstrip(',')
    json_style = body.lstrip().startswith('"')
    add = ('"audience":"%s","brief":"%s"' if json_style else "audience:'%s',brief:'%s'") % (aud, brief)
    lines[i] = '%s%s%s%s:{%s,%s}%s' % (indent, q, key, q, body, add, comma)
    done.add(hit[0])
missing = [x[0] for x in AGES if x[0] not in done]
assert not missing, missing
s = s[:a] + '\n'.join(lines) + s[b:]
