"""ต่อท้ายบันทึกการอัปเดตวันที่ 27 ต.ค. 2569 รอบสอง (อัปเดตวันเดียวกันให้ต่อในรายการเดิม ตามกติกา patch notes) รันซ้ำได้ (ใส่แล้วจะข้าม)
ต้องรัน _home_patch_notes_1027.py ก่อน แล้วต่อด้วย python tools/build-home-lite.py"""
import io
from pathlib import Path

root = Path(__file__).resolve().parents[2]
DATE, VERSION = '2026-10-27', '2.11.0'
NOTES = [
    'หนุมานพิชิตเส้นทาง (ป.4) ปรับโฉมใหม่: ปั้นหนุมาน ยักษ์ ประตูวิเศษ และของตกแต่งทุกชิ้นใหม่แบบตุ๊กตาของเล่นมีเส้นขอบการ์ตูน กระดานเป็นเกาะลอยฟ้าบนทะเลเมฆ ท้องฟ้าเปลี่ยนสีตามขั้นตอน (ฟ้าใส ยามเย็น ม่วงทอง) หน้าจอธีมพลับพลาทอง · กติกาด่านออกแบบเอง (Y001) เปลี่ยนเป็นทางเดินยาวอย่างน้อย 7 ช่อง (จากเดิม 8) ส่วนกติกาอื่นและโจทย์ทุกด่านเหมือนเดิม',
    'เกมฝึกทักษะทั้ง 4 เกมและหนุมานพิชิตเส้นทาง ย้ายตัวเกมไปฝากไว้ที่ GitHub Pages แล้วฝังด้วยลิงก์ เพื่อให้เว็บไซต์ไม่เต็มโควตาและโหลดเร็วขึ้น เปิดเล่นที่หน้าเดิมบน krukan.in.th ได้เหมือนเดิม',
]

p = root / 'Home-Play-Learn-Gaming.html'
s = io.open(p, encoding='utf-8').read()
head = "{date:'%s', version:'%s', notes:[\n" % (DATE, VERSION)
assert s.count(head) == 1, 'ยังไม่มีบันทึกวันที่ %s' % DATE
i = s.index(head); j = s.index("\n        ]},", i)
if NOTES[0] in s[i:j]:
    print('ต่อบันทึกรอบสองไว้แล้ว ข้าม')
else:
    s = s[:j] + ',\n' + ',\n'.join("          '%s'" % n for n in NOTES) + s[j:]
    io.open(p, 'w', encoding='utf-8', newline='').write(s)
    print('ต่อบันทึก %s อีก %d ข้อ' % (DATE, len(NOTES)))
