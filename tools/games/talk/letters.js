    l: [0.1, [[L(0.05, 0, 0.05, 2)]]],
    m: [1.3, [[L(0, 1, 0, 2)], [A(0.325, 1.38, 0.325, 0.38, 180, 360), L(0.65, 1.38, 0.65, 2)], [A(0.975, 1.38, 0.325, 0.38, 180, 360), L(1.3, 1.38, 1.3, 2)]]],
    n: [0.84, [[L(0, 1, 0, 2)], [A(0.42, 1.42, 0.42, 0.42, 180, 360), L(0.84, 1.42, 0.84, 2)]]],
