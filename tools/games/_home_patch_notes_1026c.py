"""ต่อท้ายบันทึกการอัปเดตวันที่ 26 ต.ค. 2569 รอบเย็น (อัปเดตวันเดียวกันให้ต่อในรายการเดิม ตามกติกา patch notes) รันซ้ำได้ (ใส่แล้วจะข้าม)
ต้องรัน _home_patch_notes_1026.py และ _home_patch_notes_1026b.py ก่อน แล้วต่อด้วย python tools/build-home-lite.py"""
import io
from pathlib import Path

root = Path(__file__).resolve().parents[2]
DATE, VERSION = '2026-10-26', '2.10.0'
NOTES = [
    'จอมพิมพ์ แป้นพิมพ์บนจอหน้าตาเหมือนคีย์บอร์ดจริง ปุ่มนูน กดแล้วยุบ มีไฟ Caps Lock · สระและวรรณยุกต์บนปุ่มไม่มีวงกลมจุดแล้ว · ตัวที่ต้องกด Shift ปุ่ม Shift ติดไฟสีส้มพร้อมป้าย กด Shift ค้างไว้ และระหว่างกด Shift ค้างทุกปุ่มสลับให้เห็นตัวบน',
    'จอมพิมพ์ ก่อนเริ่มทุกด่านให้เลือกโหมด จับเวลา หรือ ไม่จับเวลา (กด 1 หรือ 2 ส่วน Enter คือโหมดที่เล่นล่าสุด)',
    'ทุกเกมเล่นบน iPad ได้ดีขึ้น: ใส่ชื่อด้วยแป้นในเกมไม่เรียกคีย์บอร์ดของเครื่อง กรอบเกมจึงไม่เลื่อนค้าง ไม่เด้งชวนเต็มจอตอนเริ่ม และกดเต็มจอแล้วปุ่ม แตะเพื่อเล่น ไม่กดทะลุไปโดนปุ่มในเกม (แก้สมรภูมิคณิตที่กดเต็มจอแล้วเล่นต่อไม่ได้) · บนคอมพิวเตอร์ปุ่มเต็มจอบอกให้กด F11',
]

p = root / 'Home-Play-Learn-Gaming.html'
s = io.open(p, encoding='utf-8').read()
head = "{date:'%s', version:'%s', notes:[\n" % (DATE, VERSION)
assert s.count(head) == 1, 'ยังไม่มีบันทึกวันที่ %s' % DATE
i = s.index(head); j = s.index("\n        ]},", i)
if NOTES[0] in s[i:j]:
    print('ต่อบันทึกรอบเย็นไว้แล้ว ข้าม')
else:
    s = s[:j] + ',\n' + ',\n'.join("          '%s'" % n for n in NOTES) + s[j:]
    io.open(p, 'w', encoding='utf-8', newline='').write(s)
    print('ต่อบันทึก %s อีก %d ข้อ' % (DATE, len(NOTES)))
